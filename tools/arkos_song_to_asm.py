#!/usr/bin/env python3
"""Converts an Arkos Tracker .aks song to a z88dk-linkable .asm file for
lib/pico_music.h, using Arkos Tracker 3's own bundled SongToAkg CLI tool.

z88dk's own support/arkos/arkos-song-to-asm.pl (the OFFICIAL converter
script) was written against Arkos Tracker 2's SongToAkg CLI syntax, which
has changed in Arkos Tracker 3 -- that script's own `-sppostlbl :` option
no longer exists (confirmed directly: AT3's SongToAkg rejects it as an
unknown option). This script targets AT3's current CLI instead, confirmed
working end to end (export, assemble, link, AND real AY playback verified
via a waveform capture -- see docs/music-notes.md) against a real track,
not just reasoned from the help text.

Two real differences from the old AT2-era script, both handled here:

1. AT3's own SongToAkg emits bare labels with no trailing colon
   (`MyLabel` instead of `MyLabel:`) -- z88dk's own assembler requires
   the colon. The old AT2 CLI had a `-sppostlbl` flag to control this;
   AT3 dropped it. This script post-processes the output, adding a `:`
   to any line that's just a bare identifier (every real label in this
   output has nothing else on its line; every data/instruction line
   does, so this is a safe, unambiguous rewrite).
2. This script also prepends `SECTION rodata_user` + `PUBLIC
   _<symbol>_Start` (matching the old perl script's own wrapping), and
   passes `--labelPrefix _<symbol>_` to SongToAkg so the entry label
   comes out as `_<symbol>_Start` directly -- declare the C-side extern
   WITHOUT the leading underscore (`extern uint8_t <symbol>_Start[];`);
   sccz80 adds its own leading underscore to every C symbol it compiles,
   so a C name with no underscore is what actually matches an asm label
   that already has one baked in.

Requires a local Arkos Tracker 3 install (https://www.julien-nevo.com/
arkostracker/) -- point --arkos-path at it (the directory containing its
own `tools/` subfolder). The bundled SongToAkg binary may need a one-time
local re-sign if macOS rejects it with "invalid signature" (a broken
ad-hoc signature from the download/zip step, not a real security issue):

    codesign --force --deep --sign - <arkos-path>/tools/SongToAkg

Usage:
    python3 tools/arkos_song_to_asm.py --arkos-path /path/to/ArkosTracker3 \\
        --symbol my_song --out my_song.asm my_song.aks

Then in game code:
    extern uint8_t my_song_Start[];
    pico_music_init(my_song_Start, 0);
"""
import argparse
import re
import subprocess
import sys
import tempfile
import os

LABEL_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("aks", help="input .aks song file")
    ap.add_argument("--out", required=True, help="output .asm file")
    ap.add_argument("--symbol", required=True, help="base symbol name (the entry point becomes <symbol>_Start)")
    ap.add_argument("--arkos-path", required=True, help="Arkos Tracker 3 install directory (containing tools/SongToAkg)")
    args = ap.parse_args()

    song_to_akg = os.path.join(args.arkos_path, "tools", "SongToAkg")
    if not os.path.isfile(song_to_akg):
        sys.exit("SongToAkg not found at %s -- check --arkos-path" % song_to_akg)

    label_prefix = "_%s_" % args.symbol

    with tempfile.NamedTemporaryFile(suffix=".asm", delete=False) as tmp:
        tmp_path = tmp.name
    try:
        result = subprocess.run(
            [song_to_akg, "--labelPrefix", label_prefix, args.aks, tmp_path],
            capture_output=True, text=True,
        )
        if result.returncode != 0:
            sys.exit("SongToAkg failed (exit %d):\n%s\n%s" % (result.returncode, result.stdout, result.stderr))

        with open(tmp_path, "r", encoding="utf-8", errors="replace") as f:
            raw_lines = f.readlines()
    finally:
        os.unlink(tmp_path)

    out_lines = []
    for line in raw_lines:
        stripped = line.rstrip("\n")
        if LABEL_RE.match(stripped):
            out_lines.append(stripped + ":\n")
        else:
            out_lines.append(line)

    with open(args.out, "w") as f:
        f.write("; Auto-generated by tools/arkos_song_to_asm.py from %s -- do not hand-edit.\n" % args.aks)
        f.write("SECTION rodata_user\n")
        f.write("PUBLIC %s%s\n" % (label_prefix, "Start"))
        f.writelines(out_lines)

    print("wrote %s (entry point: %sStart -- declare as `extern uint8_t %sStart[];` in C, no leading underscore)" % (
        args.out, label_prefix, "%s_" % args.symbol))


if __name__ == "__main__":
    main()
