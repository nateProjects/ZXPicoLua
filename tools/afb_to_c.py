#!/usr/bin/env python3
"""Converts an AYFX .afb effects bank (Shiru's format, see
lib/pico_ayfx_player.asm's own top comment) to a C byte array for
lib/pico_ayfx.h's pico_ayfx_init(). The .afb file's own bytes are an
opaque blob to this script -- AFXPLAY (the vendored player) parses the
format itself at runtime; this just embeds the raw bytes as-is, same
relationship p8_sfx_to_c.py's own converter has to the player it feeds
(no reimplementation of the format here, by design)."""
import argparse
import sys


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("afb", help="input .afb effects bank file")
    ap.add_argument("--out", required=True, help="output .c file")
    ap.add_argument("--symbol", required=True, help="C array name")
    args = ap.parse_args()

    data = open(args.afb, "rb").read()

    with open(args.out, "w") as f:
        f.write(f"/* Auto-generated by tools/afb_to_c.py from {args.afb} -- do not hand-edit. */\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"const uint8_t {args.symbol}[{len(data)}] = {{\n")
        for i in range(0, len(data), 16):
            row = data[i:i + 16]
            f.write("    " + ", ".join(str(b) for b in row) + ",\n")
        f.write("};\n")

    print(f"wrote {args.out}: {len(data)} bytes from {args.afb}")


if __name__ == "__main__":
    sys.exit(main())
