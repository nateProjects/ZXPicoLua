#!/usr/bin/env python3
"""Converts a Pico-8 .p8 cart's __map__ (and __gff__, if present) sections
into a C source file usable with ZXPicoLua's pico_map_init()/pico_fset_all()
(lib/pico_map.h).

__map__ is already a plain, row-major grid of 2-hex-digit tile indices (one
byte per cell, 0-255, same as a sprite index) -- no bit-packing to undo, so
this is a direct hex-to-bytes decode, not a real "conversion". __gff__ (the
8 sprite flags Pico-8 keeps per sprite index, used by fget()/fset()) is the
same: one hex-pair byte per sprite index, up to 256 bytes total.

Known limitation: pre-0.2.0 Pico-8 carts could extend the map into the
bottom half of the __gfx__ section's own memory (rows 32-63) when a cart's
sprite sheet didn't need the full 128x128 area -- that legacy sharing is
NOT handled here, only the dedicated __map__ section's own rows. Every
cart this tool has actually been run against (see docs/p8-map-convert-
notes.md) uses __map__ directly and doesn't need it.

Usage:
    python3 tools/p8_map_to_c.py cart.p8 --out map_data.c --symbol my_map

Emits (into --out):
    const uint16_t <symbol>_w, <symbol>_h;            -- map dimensions, in cells
    const uint8_t  <symbol>_data[<symbol>_w*<symbol>_h]; -- row-major tile indices
    const uint8_t  <symbol>_flags[N];                  -- only if __gff__ present;
                                                            N <= 256, one byte per
                                                            sprite index (fget()'s
                                                            own whole-byte form)

_data is ready for pico_map_init(). _flags is NOT directly linkable into
pico_map.c's own internal flag table (that's deliberately static/private) --
loop pico_fset_all(i, <symbol>_flags[i]) once at startup instead.
"""
import argparse
import sys


def parse_cart_section(text, section_name):
    """Returns the raw lines of a __section_name__ block, up to the next
    __..__ marker or EOF. Pico-8's own .p8 text format is just these
    markers as bare lines, data lines in between."""
    lines = text.splitlines()
    start = None
    for i, line in enumerate(lines):
        if line.strip() == "__%s__" % section_name:
            start = i + 1
            break
    if start is None:
        return []
    out = []
    for line in lines[start:]:
        stripped = line.strip()
        if stripped.startswith("__") and stripped.endswith("__") and len(stripped) > 4:
            break
        out.append(line.rstrip("\n"))
    return out


def hex_line_to_bytes(line):
    line = line.strip()
    if not line:
        return b""
    if len(line) % 2 != 0:
        raise ValueError("odd-length hex line: %r" % line)
    return bytes.fromhex(line)


def emit_byte_array(f, name, data):
    f.write("const uint8_t %s[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), 20):
        chunk = data[i:i + 20]
        f.write("    " + ", ".join(str(b) for b in chunk) + ",\n")
    f.write("};\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cart", help=".p8 cart file")
    ap.add_argument("--out", required=True, help="output .c file")
    ap.add_argument("--symbol", default="p8_map", help="base name for emitted C symbols (default: p8_map)")
    args = ap.parse_args()

    text = open(args.cart, "r", encoding="utf-8", errors="replace").read()

    map_lines = parse_cart_section(text, "map")
    gff_lines = parse_cart_section(text, "gff")

    if not map_lines or all(not l.strip() for l in map_lines):
        sys.exit("no (non-empty) __map__ section found in %s" % args.cart)

    rows = [hex_line_to_bytes(l) for l in map_lines if l.strip() != ""]
    width = len(rows[0])
    for i, r in enumerate(rows):
        if len(r) != width:
            sys.exit("__map__ row %d has %d bytes, expected %d -- ragged map rows aren't supported" % (i, len(r), width))
    height = len(rows)
    map_bytes = b"".join(rows)

    gff_bytes = b"".join(hex_line_to_bytes(l) for l in gff_lines if l.strip() != "")
    if len(gff_bytes) > 256:
        gff_bytes = gff_bytes[:256]  # Pico-8's own sprite-flag table is always 256 bytes max, one per sprite index

    with open(args.out, "w") as f:
        f.write("/* Auto-generated by tools/p8_map_to_c.py from %s -- do not hand-edit. */\n" % args.cart)
        f.write("#include <stdint.h>\n\n")
        f.write("const uint16_t %s_w = %d;\n" % (args.symbol, width))
        f.write("const uint16_t %s_h = %d;\n" % (args.symbol, height))
        emit_byte_array(f, "%s_data" % args.symbol, map_bytes)
        if gff_bytes:
            f.write("\n")
            emit_byte_array(f, "%s_flags" % args.symbol, gff_bytes)

    msg = "wrote %s: %dx%d map (%d bytes)" % (args.out, width, height, len(map_bytes))
    if gff_bytes:
        msg += ", %d-byte sprite-flag table" % len(gff_bytes)
    print(msg)


if __name__ == "__main__":
    main()
